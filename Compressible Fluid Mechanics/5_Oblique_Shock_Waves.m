%[text] ### Statement
%[text] One of the most surprising moments in *Flow Visualization* comes when the researchers widen the angle of a diffuser and the flow begins to oscillate, even though the incoming water remains steady and symmetric. The hydrogen bubbles show water near one wall slowing down and then reversing direction as it encounters rising pressure. This creates a pocket of recirculating flow that pushes the main stream away from the wall. As the main stream shifts, it changes the pressure field enough to wash out the pocket. Then the pocket forms again, and the cycle repeats. What makes the demonstration so striking is that a simple change in geometry can turn a steady inflow into a repeating pattern of separation and recovery.
